/**
 * Check if a given date (YYYY-MM-DD) is a Thai public holiday.
 */
export function getThaiPublicHoliday(dateKey: string): {
  isHoliday: boolean;
  name?: string;
  isSubstitution?: boolean;
} {
  // 1. Check specific year override/substitution
  if (SPECIFIC_YEAR_HOLIDAYS[dateKey]) {
    return {
      isHoliday: true,
      name: SPECIFIC_YEAR_HOLIDAYS[dateKey].name,
      isSubstitution: SPECIFIC_YEAR_HOLIDAYS[dateKey].isSubstitution,
    };
  }

  // 2. Check annual fixed holiday
  const parts = dateKey.split('-');
  if (parts.length === 3) {
    const mmdd = `${parts[1]}-${parts[2]}`;
    if (FIXED_ANNUAL_HOLIDAYS[mmdd]) {
      return {
        isHoliday: true,
        name: FIXED_ANNUAL_HOLIDAYS[mmdd],
        isSubstitution: false,
      };
    }
  }

  return { isHoliday: false };
}

/**
 * Check if a given date (YYYY-MM-DD) is Wan Phra (Buddhist Holy Day).
 */
export function getWanPhra(dateKey: string): {
  isWanPhra: boolean;
  description?: string;
  phase?: string;
} {
  if (WAN_PHRA_DATES[dateKey]) {
    return {
      isWanPhra: true,
      description: WAN_PHRA_DATES[dateKey].desc,
      phase: WAN_PHRA_DATES[dateKey].phase,
    };
  }

  // Algorithmic fallback for years outside 2025-2027
  try {
    const parts = dateKey.split('-');
    const year = parseInt(parts[0], 10);
    const month = parseInt(parts[1], 10) - 1;
    const day = parseInt(parts[2], 10);
    const dateObj = new Date(Date.UTC(year, month, day, 12, 0, 0));

    // Reference new moon: 2000-01-06 18:14 UTC
    const refNewMoon = Date.UTC(2000, 0, 6, 18, 14, 0);
    const synodicMonthMs = 29.530588853 * 86400000;
    const diff = (dateObj.getTime() - refNewMoon) % synodicMonthMs;
    const phaseDays = (diff < 0 ? diff + synodicMonthMs : diff) / 86400000;

    if (Math.abs(phaseDays - 7.38) <= 0.5) {
      return { isWanPhra: true, description: 'วันพระ (ขึ้น ๘ ค่ำ)', phase: 'ขึ้น ๘ ค่ำ' };
    }
    if (Math.abs(phaseDays - 14.76) <= 0.5) {
      return { isWanPhra: true, description: 'วันพระ (ขึ้น ๑๕ ค่ำ)', phase: 'ขึ้น ๑๕ ค่ำ' };
    }
    if (Math.abs(phaseDays - 22.14) <= 0.5) {
      return { isWanPhra: true, description: 'วันพระ (แรม ๘ ค่ำ)', phase: 'แรม ๘ ค่ำ' };
    }
    if (phaseDays <= 0.5 || phaseDays >= 29.0) {
      return { isWanPhra: true, description: 'วันพระ (แรม ๑๔/๑๕ ค่ำ)', phase: 'แรม ๑๕ ค่ำ' };
    }
  } catch (e) {
    // Ignore fallback errors
  }

  return { isWanPhra: false };
}

/**
 * Consolidated getter for all special day information (Holidays & Wan Phra).
 */
export function getDaySpecialInfo(dateKey: string): DaySpecialInfo {
  const holiday = getThaiPublicHoliday(dateKey);
  const wanPhra = getWanPhra(dateKey);

  return {
    isHoliday: holiday.isHoliday,
    holidayName: holiday.name,
    isSubstitution: holiday.isSubstitution,
    isWanPhra: wanPhra.isWanPhra,
    wanPhraDescription: wanPhra.description,
    wanPhraPhase: wanPhra.phase,
  };
}
